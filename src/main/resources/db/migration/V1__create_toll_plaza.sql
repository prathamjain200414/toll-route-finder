CREATE TABLE toll_plaza
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Natural key: normalised name + coordinates rounded to ~10 m. Makes the CSV import idempotent.
    plaza_key  VARCHAR(160)             NOT NULL,
    name       VARCHAR(200)             NOT NULL,
    state      VARCHAR(100),
    latitude   DOUBLE PRECISION         NOT NULL,
    longitude  DOUBLE PRECISION         NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_toll_plaza_key UNIQUE (plaza_key)
);

CREATE INDEX idx_toll_plaza_lat_lon ON toll_plaza (latitude, longitude);
